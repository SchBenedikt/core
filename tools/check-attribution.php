/**
 * Rejects AI/tool attribution in the complete Git history.
 *
 * The check reads every commit reachable from any ref, including author and
 * committer names/addresses and the full raw message body. It is deliberately
 * read-only and requires no network access.
 *
 * A shallow clone is a hard failure: it cannot prove that the whole history is
 * clean. Fetch the full history (`git fetch --unshallow`; in GitHub Actions use
 * `actions/checkout` with `fetch-depth: 0`) before running the check.
 *
 * Usage: php tools/check-attribution.php
 *
 * Exit codes:
 *   0  clean
 *   1  attribution found
 *   2  Git history unavailable or incomplete
 */

const ATTRIBUTION_MESSAGE_TERMS = [
	'co-authored-by',
	'co-authored',
	'co-author',
	'coauthor',
	'freebuff',
	'codebuff',
	'generated with',
	'generated-with',
	'generated by',
	'generated-by',
	'assisted-by',
	'ai-assisted',
	'ai generated',
	'ai-generated',
];

const ATTRIBUTION_TOOL_IDENTITIES = [
	'freebuff',
	'codebuff',
	'anthropic',
	'openai',
	'chatgpt',
	'claude',
	'copilot',
	'codex',
	'aider',
	'devin',
	'windsurf',
	'sourcegraph',
	'tabnine',
	'cursor',
	'sweep',
];

$root = dirname(__DIR__);

/**
 * @param list<string> $arguments
 *
 * @return array{int, string, string}
 */
function runGit(string $root, array $arguments): array
{
	$command = array_merge(['git', '-C', $root], $arguments);
	$process = proc_open(
		$command,
		[
			1 => ['pipe', 'w'],
			2 => ['pipe', 'w'],
		],
		$pipes,
	);

	if (!is_resource($process)) {
		return [2, '', 'Could not start git.'];
	}

	$stdout = stream_get_contents($pipes[1]);
	$stderr = stream_get_contents($pipes[2]);
	fclose($pipes[1]);
	fclose($pipes[2]);
	$status = proc_close($process);

	return [$status, (string) $stdout, (string) $stderr];
}

/**
 * @param list<string> $terms
 */
function firstTerm(string $value, array $terms): ?string
{
	foreach ($terms as $term) {
		if (stripos($value, $term) !== false) {
			return $term;
		}
	}

	return null;
}

/**
 * Tool names are accepted in a trailer-shaped line such as `Tool: Cursor`.
 * A bare mention of a normal word in prose must not fail the guard.
 */
function toolTrailer(string $line): ?string
{
	if (preg_match('/^\s*(?:tool|ai|assistant)\s*[:\-]\s*(.*)$/i', $line, $match) !== 1) {
		return null;
	}

	return firstTerm($match[1], ATTRIBUTION_TOOL_IDENTITIES);
}

/**
 * @return list<array{commit: string, field: string, line: int, term: string, text: string}>
 */
function findAttribution(string $hash, string $field, string $value, int &$lineOffset): array
{
	$found = [];
	$lines = preg_split('/\R/', $value) ?: [];

	foreach ($lines as $index => $line) {
		$term = firstTerm($line, ATTRIBUTION_MESSAGE_TERMS);
		$term ??= toolTrailer($line);
		$lineOffset++;

		if ($term === null) {
			continue;
		}

		$found[] = [
			'commit' => $hash,
			'field' => $field,
			'line' => $lineOffset,
			'term' => $term,
			'text' => $line,
		];
	}

	return $found;
}

[$status, $shallow, $shallowError] = runGit($root, ['rev-parse', '--is-shallow-repository']);
if ($status !== 0) {
	fwrite(STDERR, "attribution guard: cannot inspect Git history: {$shallowError}\n");
	exit(2);
}

if (trim($shallow) === 'true') {
	fwrite(
		STDERR,
		"attribution guard: shallow clone; fetch the complete history first "
		. "(git fetch --unshallow; CI: actions/checkout fetch-depth: 0).\n",
	);
	exit(2);
}

$format = '%H%x00%an%x00%ae%x00%cn%x00%ce%x00%B%x00';
[$status, $raw, $error] = runGit($root, [
	'--no-pager',
	'log',
	'--all',
	'--no-color',
	'--no-show-signature',
	'--format=' . $format,
]);

if ($status !== 0) {
	fwrite(STDERR, "attribution guard: cannot read Git history: {$error}\n");
	exit(2);
}

$fields = explode("\0", $raw);
$violations = [];
$commitCount = 0;

for ($index = 0; $index + 5 < count($fields);) {
	$hash = trim($fields[$index]);
	if ($hash === '') {
		$index++;
		continue;
	}

	$authorName = $fields[$index + 1];
	$authorEmail = $fields[$index + 2];
	$committerName = $fields[$index + 3];
	$committerEmail = $fields[$index + 4];
	$message = $fields[$index + 5];
	$index += 6;
	$commitCount++;

	$identities = [
		'author' => $authorName . ' <' . $authorEmail . '>',
		'committer' => $committerName . ' <' . $committerEmail . '>',
	];

	foreach ($identities as $field => $identity) {
		$term = firstTerm($identity, ATTRIBUTION_TOOL_IDENTITIES);
		if ($term === null) {
			continue;
		}

		$violations[] = [
			'commit' => $hash,
			'field' => $field,
			'line' => 1,
			'term' => $term,
			'text' => $identity,
		];
	}

	$lineOffset = 0;
	foreach (findAttribution($hash, 'message', $message, $lineOffset) as $violation) {
		$violations[] = $violation;
	}
}

if ($commitCount === 0) {
	fwrite(STDERR, "attribution guard: no commits found; cannot prove the history.\n");
	exit(2);
}

if ($violations !== []) {
	fwrite(STDERR, 'attribution guard failed: ' . count($violations) . " match(es).\n");

	foreach ($violations as $violation) {
		$text = trim($violation['text']);
		if (mb_strlen($text) > 180) {
			$text = mb_substr($text, 0, 177) . '...';
		}

		fwrite(
			STDERR,
			sprintf(
				"  %s %s:%d [%s] %s\n",
				substr($violation['commit'], 0, 12),
				$violation['field'],
				$violation['line'],
				$violation['term'],
				$text,
			),
		);
	}

	exit(1);
}

echo 'attribution ok: ' . $commitCount . " commit(s) checked\n";
