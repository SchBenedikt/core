namespace AlohaSocial\Core\Domain\Recommendation;

use AlohaSocial\Core\Platform\Db\Connection;
use AlohaSocial\Core\Platform\Db\DatabaseException;
use AlohaSocial\Core\Support\Time;
use DateTimeImmutable;
use JsonException;
use Throwable;

use function array_map;
use function is_array;
use function is_string;
use function json_decode;
use function json_encode;

use const JSON_THROW_ON_ERROR;

/**
 * SQL storage for preferences, feedback and consented signals.
 *
 * Every write is scoped by the owner id. The feedback primary key makes a
 * changed verdict an update, and signal ids are generated by the service so a
 * retry can be idempotent without a scan.
 */
final class PdoRecommendationRepository implements RecommendationRepository
{
	private const PREFERENCE_COLUMNS = 'user_id, enabled, behavioral_consent, interests_json, languages_json, updated_at';

	private const FEEDBACK_COLUMNS = 'user_id, candidate_id, action, created_at';

	private const SIGNAL_COLUMNS = 'id, user_id, kind, candidate_id, created_at';

	public function __construct(
		private readonly Connection $db,
	) {
	}

	public function preference(string $userId): ?RecommendationPreference
	{
		$row = $this->db->fetchOne(
			'SELECT ' . self::PREFERENCE_COLUMNS . ' FROM ' . RecommendationSchema::PREFERENCE_TABLE
			. ' WHERE user_id = :user_id',
			['user_id' => $userId],
		);

		return $row === null ? null : $this->hydratePreference($row);
	}

	public function savePreference(RecommendationPreference $preference): void
	{
		try {
			$parameters = [
				'user_id' => $preference->userId,
				'enabled' => $preference->enabled ? 1 : 0,
				'behavioral_consent' => $preference->behavioralConsent ? 1 : 0,
				'interests_json' => json_encode($preference->interests, JSON_THROW_ON_ERROR),
				'languages_json' => json_encode($preference->languages, JSON_THROW_ON_ERROR),
				'updated_at' => Time::format($preference->updatedAt),
			];
		} catch (JsonException $exception) {
			throw new DatabaseException('Recommendation preferences could not be encoded.', 0, $exception);
		}

		if ($this->preference($preference->userId) !== null) {
			$this->db->execute(
				'UPDATE ' . RecommendationSchema::PREFERENCE_TABLE . ' SET'
				. ' enabled = :enabled, behavioral_consent = :behavioral_consent,'
				. ' interests_json = :interests_json, languages_json = :languages_json, updated_at = :updated_at'
				. ' WHERE user_id = :user_id',
				$parameters,
			);

			return;
		}

		try {
			$this->db->execute(
				'INSERT INTO ' . RecommendationSchema::PREFERENCE_TABLE
				. ' (' . self::PREFERENCE_COLUMNS . ') VALUES ('
				. ' :user_id, :enabled, :behavioral_consent, :interests_json, :languages_json, :updated_at)',
				$parameters,
			);
		} catch (Throwable $exception) {
			throw new DatabaseException('Recommendation preferences could not be stored.', 0, $exception);
		}
	}

	public function deletePreference(string $userId): void
	{
		$this->db->execute(
			'DELETE FROM ' . RecommendationSchema::PREFERENCE_TABLE . ' WHERE user_id = :user_id',
			['user_id' => $userId],
		);
	}

	public function feedback(string $userId, string $candidateId): ?RecommendationFeedback
	{
		$row = $this->db->fetchOne(
			'SELECT ' . self::FEEDBACK_COLUMNS . ' FROM ' . RecommendationSchema::FEEDBACK_TABLE
			. ' WHERE user_id = :user_id AND candidate_id = :candidate_id',
			['user_id' => $userId, 'candidate_id' => $candidateId],
		);

		return $row === null ? null : $this->hydrateFeedback($row);
	}

	public function feedbackFor(string $userId): array
	{
		$rows = $this->db->fetchAll(
			'SELECT ' . self::FEEDBACK_COLUMNS . ' FROM ' . RecommendationSchema::FEEDBACK_TABLE
			. ' WHERE user_id = :user_id ORDER BY created_at DESC, candidate_id ASC',
			['user_id' => $userId],
		);

		return array_map(fn (array $row): RecommendationFeedback => $this->hydrateFeedback($row), $rows);
	}

	public function saveFeedback(RecommendationFeedback $feedback): void
	{
		$parameters = [
			'user_id' => $feedback->userId,
			'candidate_id' => $feedback->candidateId,
			'action' => $feedback->kind->value,
			'created_at' => Time::format($feedback->createdAt),
		];

		if ($this->feedback($feedback->userId, $feedback->candidateId) !== null) {
			$this->db->execute(
				'UPDATE ' . RecommendationSchema::FEEDBACK_TABLE . ' SET action = :action, created_at = :created_at'
				. ' WHERE user_id = :user_id AND candidate_id = :candidate_id',
				$parameters,
			);

			return;
		}

		try {
			$this->db->execute(
				'INSERT INTO ' . RecommendationSchema::FEEDBACK_TABLE
				. ' (' . self::FEEDBACK_COLUMNS . ') VALUES ('
				. ' :user_id, :candidate_id, :action, :created_at)',
				$parameters,
			);
		} catch (Throwable $exception) {
			throw new DatabaseException('Recommendation feedback could not be stored.', 0, $exception);
		}
	}

	public function deleteFeedback(string $userId, string $candidateId): bool
	{
		return $this->db->execute(
			'DELETE FROM ' . RecommendationSchema::FEEDBACK_TABLE
			. ' WHERE user_id = :user_id AND candidate_id = :candidate_id',
			['user_id' => $userId, 'candidate_id' => $candidateId],
		) > 0;
	}

	public function deleteFeedbackFor(string $userId): void
	{
		$this->db->execute(
			'DELETE FROM ' . RecommendationSchema::FEEDBACK_TABLE . ' WHERE user_id = :user_id',
			['user_id' => $userId],
		);
	}

	public function appendSignal(RecommendationSignal $signal): void
	{
		try {
			$this->db->execute(
				'INSERT INTO ' . RecommendationSchema::SIGNAL_TABLE
				. ' (' . self::SIGNAL_COLUMNS . ') VALUES ('
				. ' :id, :user_id, :kind, :candidate_id, :created_at)',
				[
					'id' => $signal->id,
					'user_id' => $signal->userId,
					'kind' => $signal->kind->value,
					'candidate_id' => $signal->candidateId,
					'created_at' => Time::format($signal->createdAt),
				],
			);
		} catch (Throwable $exception) {
			throw new DatabaseException('A recommendation signal could not be stored.', 0, $exception);
		}
	}

	public function signalsFor(string $userId, int $limit = 1000): array
	{
		$limit = max(1, min(1000, $limit));
		$rows = $this->db->fetchAll(
			'SELECT ' . self::SIGNAL_COLUMNS . ' FROM ' . RecommendationSchema::SIGNAL_TABLE
			. ' WHERE user_id = :user_id ORDER BY created_at DESC, id DESC LIMIT ' . $limit,
			['user_id' => $userId],
		);

		return array_map(fn (array $row): RecommendationSignal => $this->hydrateSignal($row), $rows);
	}

	public function signalCount(string $userId): int
	{
		$value = $this->db->fetchValue(
			'SELECT COUNT(*) FROM ' . RecommendationSchema::SIGNAL_TABLE . ' WHERE user_id = :user_id',
			['user_id' => $userId],
		);

		return (int) $value;
	}

	public function recentSignal(
		string $userId,
		RecommendationSignalKind $kind,
		string $candidateId,
		DateTimeImmutable $since,
	): ?RecommendationSignal {
		$row = $this->db->fetchOne(
			'SELECT ' . self::SIGNAL_COLUMNS . ' FROM ' . RecommendationSchema::SIGNAL_TABLE
			. ' WHERE user_id = :user_id AND kind = :kind AND candidate_id = :candidate_id'
			. ' AND created_at >= :since ORDER BY created_at DESC, id DESC LIMIT 1',
			[
				'user_id' => $userId,
				'kind' => $kind->value,
				'candidate_id' => $candidateId,
				'since' => Time::format($since),
			],
		);

		return $row === null ? null : $this->hydrateSignal($row);
	}

	public function deleteSignalsFor(string $userId): void
	{
		$this->db->execute(
			'DELETE FROM ' . RecommendationSchema::SIGNAL_TABLE . ' WHERE user_id = :user_id',
			['user_id' => $userId],
		);
	}

	public function deleteForUser(string $userId): void
	{
		$this->db->transaction(function () use ($userId): void {
			$this->deletePreference($userId);
			$this->deleteFeedbackFor($userId);
			$this->deleteSignalsFor($userId);
		});
	}

	/**
	 * @param array<string, mixed> $row
	 */
	private function hydratePreference(array $row): RecommendationPreference
	{
		$interests = $this->decodeStringList((string) $row['interests_json']);
		$languages = $this->decodeStringList((string) $row['languages_json']);

		return new RecommendationPreference(
			(string) $row['user_id'],
			(int) $row['enabled'] === 1,
			(int) $row['behavioral_consent'] === 1,
			$interests,
			$languages,
			Time::parse((string) $row['updated_at']),
		);
	}

	/**
	 * @param array<string, mixed> $row
	 */
	private function hydrateFeedback(array $row): RecommendationFeedback
	{
		$kind = RecommendationFeedbackKind::tryFrom((string) $row['action']);
		if ($kind === null) {
			throw new DatabaseException('Stored recommendation feedback has an unknown action.');
		}

		return new RecommendationFeedback(
			(string) $row['user_id'],
			(string) $row['candidate_id'],
			$kind,
			Time::parse((string) $row['created_at']),
		);
	}

	/**
	 * @param array<string, mixed> $row
	 */
	private function hydrateSignal(array $row): RecommendationSignal
	{
		$kind = RecommendationSignalKind::tryFrom((string) $row['kind']);
		if ($kind === null) {
			throw new DatabaseException('A stored recommendation signal has an unknown kind.');
		}

		return new RecommendationSignal(
			(string) $row['id'],
			(string) $row['user_id'],
			$kind,
			(string) $row['candidate_id'],
			Time::parse((string) $row['created_at']),
		);
	}

	/**
	 * @return list<string>
	 */
	private function decodeStringList(string $json): array
	{
		try {
			$value = json_decode($json, true, 16, JSON_THROW_ON_ERROR);
		} catch (JsonException $exception) {
			throw new DatabaseException('Stored recommendation preferences are unreadable.', 0, $exception);
		}

		if (!is_array($value) || !array_is_list($value)) {
			throw new DatabaseException('Stored recommendation preferences are not a list.');
		}

		$result = [];
		foreach ($value as $entry) {
			if (!is_string($entry)) {
				throw new DatabaseException('Stored recommendation preferences contain a non-string value.');
			}

			$result[] = $entry;
		}

		return $result;
	}
}
